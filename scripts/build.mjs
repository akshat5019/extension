import { build } from 'esbuild';
import { mkdir, copyFile, cp } from 'node:fs/promises';
await mkdir('dist', { recursive: true });
await cp('icons', 'dist/icons', { recursive: true });
await build({ entryPoints: ['src/popup.js', 'src/content.js', 'src/background.js'], outdir: 'dist', bundle: true, format: 'iife', target: 'chrome120', logLevel: 'info' });
await copyFile('node_modules/pdfjs-dist/build/pdf.worker.mjs', 'dist/pdf.worker.mjs');
await cp('node_modules/pdfjs-dist/wasm', 'dist/wasm', { recursive: true });
await cp('node_modules/pdfjs-dist/standard_fonts', 'dist/standard_fonts', { recursive: true });
await cp('node_modules/pdfjs-dist/cmaps', 'dist/cmaps', { recursive: true });
for (const name of ['manifest.json', 'popup.html', 'popup.css']) await copyFile(name, `dist/${name}`);
